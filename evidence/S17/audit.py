base = read('evidence/S17/baseline.json')
old = json.loads(subprocess.check_output(['git','show',base['base_commit']+':plan/coverage.json'], cwd=ROOT, text=True))
current = read('plan/coverage.json')
assert len(old['items']) == len(current['items']) == 83
rows, missing = [], []
for item, before in zip(current['items'], old['items']):
    for key in before:
        if key != 'actual_evidence':
            assert item[key] == before[key], (item['id'], key)
    assert set(before.get('actual_evidence', [])) <= set(item.get('actual_evidence', []))
    sid = item['id']
    observed, gap = ASSESSMENTS[sid] if not sid.startswith('C') else ('Сохранённое положение/contract/questions; безопасный статус без имитации события', CONTEST_GAPS[int(sid[1:])])
    evidence = before.get('actual_evidence', [])
    for path in evidence:
        if not (ROOT / path).is_file(): missing.append({'id':sid,'path':path})
    rows.append({'id':sid,'text':item['text'],'status':item['fulfilment_status'],'observed':observed,'remaining':gap,'evidence':evidence,'subchecks':item['subchecks']})
assert not missing, missing
assert sum(len(r['subchecks']) for r in rows) == 160
